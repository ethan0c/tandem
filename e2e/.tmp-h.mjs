import { chromium } from "playwright";
const label = process.argv[2];
const TITLE = "share-" + Date.now().toString(36);
const b = await chromium.launch({ channel: "chrome", headless: false, args: ["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream", `--auto-select-tab-capture-source-by-title=${TITLE}`, "--autoplay-policy=no-user-gesture-required"] });
const tabCtx = await b.newContext({ viewport: { width: 1920, height: 1080 } });
const tab = await tabCtx.newPage();
await tab.setContent(`<title>${TITLE}</title><body style="margin:0;background:#123"><video id=v autoplay muted loop style="display:none"></video><canvas id=c width=1920 height=1080></canvas><script>const x=c.getContext('2d');let i=0;(function f(){x.fillStyle='hsl('+(i%360)+',60%,40%)';x.fillRect(0,0,1920,1080);for(let k=0;k<40;k++){x.fillStyle='hsl('+((i*3+k*9)%360)+',80%,60%)';x.fillRect((i*7+k*45)%1920,(k*27+i*3)%1080,120,80)}x.fillStyle='#fff';x.font='48px sans-serif';x.fillText('frame '+i,40,80);i++;requestAnimationFrame(f)})()</script>`);
const room = "h-" + Date.now().toString(36);
async function open(name) {
  const ctx = await b.newContext({ permissions: ["camera", "microphone"], screen: { width: 1920, height: 1080 } });
  await ctx.addInitScript(() => { window.__pcs = []; const PC = window.RTCPeerConnection; window.RTCPeerConnection = class extends PC { constructor(...a) { super(...a); window.__pcs.push(this); } }; });
  const p = await ctx.newPage();
  await p.goto("http://localhost:3000/room/" + room);
  await p.waitForFunction(() => { const x = document.querySelector('button[aria-label*="microphone"]'); return x && !x.disabled; });
  await p.getByLabel("Your name").fill(name);
  return p;
}
const a = await open("Alice"); await a.getByRole("button", { name: "Join room", exact: true }).click(); await a.waitForTimeout(800);
const bp = await open("Bob"); await bp.getByRole("button", { name: "Join room", exact: true }).click();
await bp.waitForFunction(() => [...document.querySelectorAll("video.object-cover")].some((v) => !v.muted && v.videoWidth > 0), null, { timeout: 40000 });
await a.waitForTimeout(1500);
await a.getByRole("button", { name: "Choose a video" }).click();
await a.waitForTimeout(800);
const camFrames = () => bp.evaluate(() => [...document.querySelectorAll("video.object-cover")].find((v) => !v.muted && v.videoWidth > 0)?.getVideoPlaybackQuality().totalVideoFrames ?? 0);
const c0 = await camFrames();
const t1 = Date.now();
await a.getByRole("button", { name: "Choose a tab to share" }).click();
await bp.waitForFunction(() => { const v = document.querySelector("video.object-contain"); return v && v.videoWidth > 0; }, null, { timeout: 30000, polling: 20 });
const startMs = Date.now() - t1;
const camFps = (await camFrames() - c0) / ((Date.now() - t1) / 1000);
await a.waitForTimeout(8000);
const stats = await a.evaluate(async () => { for (const pc of window.__pcs) for (const s of (await pc.getStats()).values()) if (s.type === "outbound-rtp" && s.kind === "video" && s.frameWidth >= 960) return { impl: s.encoderImplementation, w: s.frameWidth, h: s.frameHeight, fps: s.framesPerSecond, limit: s.qualityLimitationReason, kbps: Math.round(s.targetBitrate / 1000) }; });
const viewer = await bp.evaluate(() => { const v = document.querySelector("video.object-contain"); return `${v.videoWidth}x${v.videoHeight}`; });
console.log(`${label}: share first frame ${startMs} ms | camera kept ${camFps.toFixed(0)} fps meanwhile | after 8 s: ${JSON.stringify(stats)} viewer ${viewer}`);
await b.close();
